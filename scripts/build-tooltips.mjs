// Resolve tooltip definitions against the keymap and emit a flat lookup table.
//
//     node scripts/build-tooltips.mjs [outfile]     (default: dist/tooltips.json)
//
// Definitions in site/tooltips.mjs match on BINDING, never on key position, so
// they survive layout changes. This script does the binding -> position lookup
// once at build time, and fails loudly if a definition no longer matches
// anything -- which is how a rebound or deleted key gets caught.
//
// The output is deliberately renderer-agnostic:
//
//     { keys: { "<layerIndex>.<keyPosition>": "<id>" }, content: { "<id>": {...} } }

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url);
const keymapPath = fileURLToPath(new URL('config/shared/keymap.dtsi', root));
const outFile = process.argv[2] ?? 'dist/tooltips.json';
const svgPath = process.argv[3] ?? 'keymap-drawer/corne.svg';

const defs = (await import(new URL('site/tooltips.mjs', root))).default;

// --- parse the keymap -------------------------------------------------------

const source = readFileSync(keymapPath, 'utf8')
  .replace(/\/\*[\s\S]*?\*\//g, '') // block comments
  .replace(/\/\/[^\n]*/g, ''); //     line comments

// Anchored to "<name>_layer {" so an unrelated `bindings` property elsewhere in
// the file (a behaviour, say) can never be mistaken for a layer.
const layerRe =
  /(\w+)_layer\s*\{\s*display-name\s*=\s*([^;]+);[\s\S]*?bindings\s*=\s*<([\s\S]*?)>\s*;/g;

// The base layer's display-name is the KEYMAP_VERSION macro, so resolve it the
// same way the preprocessor would in order to compare against the SVG.
const versionSrc = readFileSync(fileURLToPath(new URL('config/shared/version.dtsi', root)), 'utf8');
const version = versionSrc.match(/#define\s+KEYMAP_VERSION\s+"([^"]*)"/)?.[1];

const layers = [];
for (const [, name, rawLabel, block] of source.matchAll(layerRe)) {
  const label = rawLabel.trim().replace(/^"|"$/g, '');
  const bindings = block
    .split(/(?=&)/) //             every binding starts with '&'
    .map((b) => b.replace(/\s+/g, ' ').trim())
    .filter(Boolean);
  layers.push({ name, label: label === 'KEYMAP_VERSION' ? version : label, bindings });
}

if (layers.length === 0) {
  throw new Error(`No layers parsed from ${keymapPath} - the parser is out of step with the file.`);
}

const widths = new Set(layers.map((l) => l.bindings.length));
if (widths.size !== 1) {
  const detail = layers.map((l) => `${l.name}=${l.bindings.length}`).join(', ');
  throw new Error(`Layers have differing key counts (${detail}) - parse is unreliable.`);
}

// --- resolve matches --------------------------------------------------------

const matches = (binding, pattern) => binding === pattern || binding.startsWith(`${pattern} `);

const keys = {};
const unmatched = [];
const collisions = [];

for (const [id, def] of Object.entries(defs)) {
  if (!def.match) throw new Error(`Tooltip "${id}" has no "match".`);

  let hits = 0;
  layers.forEach((layer, layerIndex) => {
    if (def.layer !== undefined && def.layer !== layerIndex) return;
    layer.bindings.forEach((binding, keyIndex) => {
      if (!matches(binding, def.match)) return;
      const slot = `${layerIndex}.${keyIndex}`;
      if (keys[slot] && keys[slot] !== id) {
        collisions.push(`${slot}: "${keys[slot]}" and "${id}"`);
        return; // first definition wins
      }
      keys[slot] = id;
      hits += 1;
    });
  });

  if (hits === 0) unmatched.push(`${id} (match: ${def.match})`);
}

if (unmatched.length > 0) {
  throw new Error(
    'These tooltips match no key in the current keymap:\n' +
      unmatched.map((u) => `  - ${u}`).join('\n') +
      '\nUpdate the "match" in site/tooltips.mjs, or remove the entry.'
  );
}

for (const c of collisions) {
  console.warn(`warning: two tooltips claim the same key, keeping the first -> ${c}`);
}

// --- verify the diagram actually matches the keymap -------------------------
//
// Positions are resolved from keymap.dtsi but applied to the rendered SVG, and
// those are separate artifacts: the SVG is regenerated by the keymap-drawer
// workflow and committed, so it lags any uncommitted keymap edit. Annotating a
// stale diagram would silently attach tooltips to the wrong keys, which is
// exactly the failure this whole binding-based scheme exists to prevent.

const svg = readFileSync(svgPath, 'utf8');
const found = [...svg.matchAll(/<g[^>]*class="layer-([^"]*)"/g)];
const svgLayers = found.map((m, i) => {
  const chunk = svg.slice(m.index, found[i + 1]?.index ?? svg.length);
  return { label: m[1], positions: new Set([...chunk.matchAll(/keypos-(\d+)/g)].map((x) => x[1])) };
});

const staleHint =
  `\n${svgPath} is out of step with ${keymapPath}.\n` +
  'Regenerate the diagram (scripts/draw.ps1 writes corne.local.svg, which this\n' +
  'build prefers when present), or push and let the drawer workflow rebuild it.';

if (svgLayers.length !== layers.length) {
  throw new Error(
    `Diagram has ${svgLayers.length} layers, keymap has ${layers.length}.${staleHint}`
  );
}

// Position counts alone cannot detect staleness -- every layer has the same 42
// slots regardless of content. Layer labels are content-derived, so comparing
// them catches a diagram drawn from a different version of the keymap.
const renamed = layers
  .map((layer, i) => ({ want: layer.label, got: svgLayers[i].label }))
  .filter(({ want, got }) => want !== got);

if (renamed.length > 0) {
  const detail = renamed.map(({ want, got }) => `"${got}" should be "${want}"`).join(', ');
  throw new Error(`Diagram layer names do not match the keymap: ${detail}.${staleHint}`);
}

const orphans = Object.keys(keys).filter((slot) => {
  const [layerIndex, keyIndex] = slot.split('.');
  return !svgLayers[layerIndex]?.positions.has(keyIndex);
});

if (orphans.length > 0) {
  throw new Error(
    `These key positions do not exist in the diagram: ${orphans.join(', ')}.${staleHint}`
  );
}

// --- emit -------------------------------------------------------------------

const content = Object.fromEntries(
  Object.entries(defs).map(([id, { match, layer, ...rest }]) => [id, rest])
);

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, `${JSON.stringify({ keys, content }, null, 1)}\n`, 'utf8');

const layerNames = layers.map((l) => l.name.replace(/_layer$/, '')).join(', ');
console.log(
  `tooltips: ${Object.keys(content).length} definitions -> ${Object.keys(keys).length} keys ` +
    `across ${layers.length} layers (${layerNames}) -> ${outFile}`
);
